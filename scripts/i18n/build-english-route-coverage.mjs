import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const ROOT = process.cwd();
const OUT_JSON = path.join(ROOT, "public/data/en-route-coverage.json");
const OUT_MD = path.join(ROOT, "docs/english-route-coverage.md");
const EXCLUDED_PREFIXES = [
  ".github/",
  "admin/",
  "assets/",
  "content/",
  "docs/",
  "node_modules/",
  "outputs/",
  "public/",
  "scripts/",
  "templates/",
  "woek-institut-app/",
];
const EXCLUDED_FILES = new Set([
  "404.html",
]);
const ENGLISH_ROUTE_OVERRIDES = new Map([
  ["bibliothek/index.html", "en/library/index.html"],
  ["app/index.html", "en/app/index.html"],
  ["mein-wirkungsraum/index.html", "en/my-impact-space/index.html"],
  ["suche.html", "en/search/index.html"],
  ["tools/index.html", "en/tools/index.html"],
  ["werkzeuge/index.html", "en/tools/index.html"],
  ["woek-ki/index.html", "en/woek-ai/index.html"],
]);

function gitFiles() {
  return execFileSync("git", ["ls-files", "*.html"], { cwd: ROOT, encoding: "utf8" })
    .trim()
    .split("\n")
    .filter(Boolean);
}

function isPublicVisibleRoute(file) {
  if (EXCLUDED_FILES.has(file)) return false;
  if (file.startsWith("en/")) return false;
  if (EXCLUDED_PREFIXES.some((prefix) => file.startsWith(prefix))) return false;
  if (!fs.existsSync(path.join(ROOT, file))) return false;
  const html = fs.readFileSync(path.join(ROOT, file), "utf8");
  if (/<meta\s+name=["']robots["']\s+content=["'][^"']*noindex/i.test(html)) return false;
  if (/http-equiv=["']refresh["']/i.test(html) && /url=/i.test(html)) return false;
  return true;
}

function routeFromFile(file) {
  if (file === "index.html") return "";
  if (file.endsWith("/index.html")) return file.slice(0, -"index.html".length);
  return file;
}

function englishFileFor(file) {
  if (ENGLISH_ROUTE_OVERRIDES.has(file)) return ENGLISH_ROUTE_OVERRIDES.get(file);
  if (file === "index.html") return "en/index.html";
  if (file.endsWith("/index.html")) return `en/${file}`;
  return `en/${file.replace(/\.html$/, "/index.html")}`;
}

function categoryFor(file) {
  const first = file.split("/")[0];
  if (file === "index.html") return "homepage";
  if (file.endsWith(".html") && !file.includes("/")) return "top-level";
  return first;
}

function titleFor(file) {
  const html = fs.readFileSync(path.join(ROOT, file), "utf8");
  const title = html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] || "";
  return title.replace(/\s+/g, " ").trim();
}

const routes = gitFiles()
  .filter(isPublicVisibleRoute)
  .map((file) => {
    const enFile = englishFileFor(file);
    return {
      sourceFile: file,
      sourceRoute: `/${routeFromFile(file)}`,
      englishFile: enFile,
      englishRoute: `/${routeFromFile(enFile)}`,
      category: categoryFor(file),
      title: titleFor(file),
      status: fs.existsSync(path.join(ROOT, enFile)) ? "available" : "missing",
    };
  })
  .sort((a, b) => a.sourceFile.localeCompare(b.sourceFile, "de"));

const byCategory = {};
for (const route of routes) {
  byCategory[route.category] ||= { total: 0, available: 0, missing: 0 };
  byCategory[route.category].total += 1;
  byCategory[route.category][route.status] += 1;
}

const counts = {
  total: routes.length,
  available: routes.filter((route) => route.status === "available").length,
  missing: routes.filter((route) => route.status === "missing").length,
  byCategory,
};

const manifest = {
  schemaVersion: "2026-07-english-visible-route-coverage",
  generatedAt: new Date().toISOString().slice(0, 10),
  scope: "Public visible HTML routes in the static website, excluding admin, assets, source folders, generated private outputs, redirects and existing English routes.",
  rule: "Every visible public German route needs an English counterpart below /en/ with translated visible text, translated UI and English-aware media/download routing.",
  counts,
  routes,
};

fs.mkdirSync(path.dirname(OUT_JSON), { recursive: true });
fs.writeFileSync(OUT_JSON, `${JSON.stringify(manifest, null, 2)}\n`);

const categoryRows = Object.entries(byCategory)
  .sort((a, b) => b[1].total - a[1].total)
  .map(([category, data]) => `| ${category} | ${data.total} | ${data.available} | ${data.missing} |`)
  .join("\n");

const missingSample = routes
  .filter((route) => route.status === "missing")
  .slice(0, 80)
  .map((route) => `| \`${route.sourceRoute}\` | \`${route.englishRoute}\` | ${route.category} | ${route.title.replaceAll("|", "\\|")} |`)
  .join("\n");

const md = `# English Route Coverage

Generated by \`scripts/i18n/build-english-route-coverage.mjs\`.

## Rule

Every visible public German route needs an English counterpart below \`/en/\` with translated visible text, translated UI and English-aware media/download routing.

## Summary

- Public visible source routes: ${counts.total}
- English routes already present: ${counts.available}
- English routes missing: ${counts.missing}

## Categories

| Category | Total | Available | Missing |
| --- | ---: | ---: | ---: |
${categoryRows}

## First Missing Routes

| German route | English target | Category | Title |
| --- | --- | --- | --- |
${missingSample}
`;

fs.mkdirSync(path.dirname(OUT_MD), { recursive: true });
fs.writeFileSync(OUT_MD, md);

console.log(`English route coverage written: ${counts.available}/${counts.total} routes available.`);
