import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const redirectsFile = path.join(root, "content", "redirects", "site-redirects.json");
const redirectsOutputFile = path.join(root, "_redirects");
const site = "https://wirkungsoekonomie.de";

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function normalizeRoute(value, field) {
  if (typeof value !== "string" || !value.trim()) {
    throw new Error(`Redirect ${field} muss eine nicht-leere Zeichenkette sein.`);
  }

  const trimmed = value.trim();
  if (/^https?:\/\//i.test(trimmed)) {
    const parsed = new URL(trimmed);
    if (parsed.hostname !== "wirkungsoekonomie.de") {
      throw new Error(`Redirect ${field} muss intern sein: ${trimmed}`);
    }
    return `${parsed.pathname}${parsed.search}${parsed.hash}`;
  }

  return trimmed.startsWith("/") ? trimmed : `/${trimmed}`;
}

function isHtmlRoute(route) {
  const clean = route.split(/[?#]/)[0];
  return clean.endsWith(".html");
}

function routeToFile(route) {
  const clean = route.split(/[?#]/)[0].replace(/^\/+/, "");
  if (!clean || clean.endsWith("/")) return path.join(root, clean, "index.html");
  if (clean.endsWith(".html")) return path.join(root, clean);
  return path.join(root, clean, "index.html");
}

function targetExists(route) {
  const clean = route.split(/[?#]/)[0];
  if (/^https?:\/\//i.test(clean)) return true;
  return fs.existsSync(routeToFile(clean));
}

function relativeTarget(fromRoute, toRoute) {
  if (/^https?:\/\//i.test(toRoute)) return toRoute;
  if (!toRoute.startsWith("/")) return toRoute;

  const sourceFile = routeToFile(fromRoute);
  const sourceDir = path.dirname(sourceFile);
  const targetClean = toRoute.split("#")[0].split("?")[0];
  const targetFile = routeToFile(targetClean);
  let relative = path.relative(sourceDir, targetFile).split(path.sep).join("/");
  if (!relative.startsWith(".")) relative = `./${relative}`;
  relative = relative.replace(/\/index\.html$/, "/");
  if (relative === "./index.html") relative = "./";

  const suffix = toRoute.slice(targetClean.length);
  return `${relative}${suffix}`;
}

function redirectHtml(entry) {
  const absoluteTarget = entry.to.startsWith("http") ? entry.to : `${site}${entry.to}`;
  const localTarget = relativeTarget(entry.from, entry.to);
  const title = entry.title || "Weiterleitung";
  const note = entry.reason || "Diese Adresse wurde durch eine neue kanonische Adresse ersetzt.";

  return `<!doctype html>
<!-- Generated by scripts/site/build-redirects.mjs. Do not edit manually. -->
<html lang="de">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta http-equiv="refresh" content="0; url=${escapeHtml(localTarget)}">
    <meta name="robots" content="noindex, follow">
    <link rel="canonical" href="${escapeHtml(absoluteTarget)}">
    <title>${escapeHtml(title)} | Wirkungsökonomie</title>
  </head>
  <body>
    <main>
      <h1>${escapeHtml(title)}</h1>
      <p>${escapeHtml(note)}</p>
      <p><a href="${escapeHtml(localTarget)}">Zur neuen Seite wechseln</a></p>
    </main>
  </body>
</html>
`;
}

function isGeneratedRedirectStub(file) {
  if (!fs.existsSync(file)) return false;
  const html = fs.readFileSync(file, "utf8");
  return html.includes("Generated by scripts/site/build-redirects.mjs")
    || (html.includes('<meta http-equiv="refresh"') && html.includes('<meta name="robots" content="noindex, follow">') && html.includes("Zur neuen Seite wechseln"));
}

function validateEntry(raw, index, defaults) {
  const entry = {
    status: Number(raw.status || defaults.status || 301),
    replaceExisting: Boolean(raw.replaceExisting ?? defaults.replaceExisting),
    allowMissingTarget: Boolean(raw.allowMissingTarget ?? defaults.allowMissingTarget),
    enabled: Boolean(raw.enabled),
    from: normalizeRoute(raw.from, `redirects[${index}].from`),
    to: normalizeRoute(raw.to, `redirects[${index}].to`),
    title: raw.title || "Weiterleitung",
    reason: raw.reason || "",
  };

  if (![301, 302, 307, 308].includes(entry.status)) {
    throw new Error(`Redirect ${entry.from}: status muss 301, 302, 307 oder 308 sein.`);
  }
  if (entry.from === entry.to) {
    throw new Error(`Redirect ${entry.from}: Quelle und Ziel duerfen nicht identisch sein.`);
  }
  if (!entry.allowMissingTarget && !targetExists(entry.to)) {
    throw new Error(`Redirect ${entry.from}: Ziel existiert nicht: ${entry.to}`);
  }

  return entry;
}

function writeRedirectStub(entry) {
  const targetFile = routeToFile(entry.from);
  if (fs.existsSync(targetFile) && !entry.replaceExisting && !isGeneratedRedirectStub(targetFile)) {
    throw new Error(`Redirect ${entry.from}: ${path.relative(root, targetFile)} existiert bereits. Setze replaceExisting=true, wenn die alte Seite ersetzt werden soll.`);
  }
  fs.mkdirSync(path.dirname(targetFile), { recursive: true });
  fs.writeFileSync(targetFile, redirectHtml(entry));
}

function writeRedirectsFile(entries) {
  const lines = [
    "# Generated by scripts/site/build-redirects.mjs from content/redirects/site-redirects.json",
    "# Static HTML redirect stubs are generated in parallel for GitHub Pages compatibility.",
    ...entries.map((entry) => `${entry.from} ${entry.to} ${entry.status}`),
    "",
  ];
  fs.writeFileSync(redirectsOutputFile, lines.join("\n"));
}

const config = readJson(redirectsFile);
const defaults = config.defaults || {};
const entries = (config.redirects || [])
  .map((entry, index) => ({ raw: entry, index }))
  .filter(({ raw }) => raw.enabled === true)
  .map(({ raw, index }) => validateEntry(raw, index, defaults));

const seen = new Set();
for (const entry of entries) {
  if (seen.has(entry.from)) throw new Error(`Redirect ${entry.from}: doppelte Quelle.`);
  seen.add(entry.from);
}

for (const entry of entries) {
  writeRedirectStub(entry);
}
writeRedirectsFile(entries);

console.log(`built redirects: ${entries.length}`);
